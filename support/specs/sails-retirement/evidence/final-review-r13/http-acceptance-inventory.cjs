'use strict';

// Generation only: requires the pinned Git baseline and installed dependencies.
// The permanent test reads the resulting JSON without calling this script/Git.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '../../../../..');
process.env.TS_NODE_PROJECT = path.join(root, 'packages/redbox-core/test/tsconfig.json');
require(path.join(root, 'node_modules/ts-node/register/transpile-only'));
const { collectInventory } = require(path.join(root, 'packages/redbox-core/test/helpers/httpInputInventory.cjs'));
const inventory = collectInventory();
const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 128 * 1024 * 1024 });
const write = (name, value) => fs.writeFileSync(path.join(__dirname, name), value);
write('http-acceptance.json', JSON.stringify(inventory, null, 2) + '\n');
const unique = new Map();
for (const row of inventory.rows) {
  const key = row.baseline.file + ':' + row.baseline.action;
  if (!unique.has(key)) unique.set(key, row);
}
write(
  'http-acceptance-inputs.txt',
  [...unique.values()]
    .map(
      row =>
        `${row.baseline.file ?? 'inline/native'}:${row.baseline.line ?? '-'} ${row.baseline.action ?? row.path}\n` +
        row.baseline.inputs
          ?.map(
            input =>
              `  ${input.line} [${input.method}] ${input.expression}\n    ${input.context.replace(/\n/g, '\n    ')}`
          )
          .join('\n')
    )
    .join('\n\n') + '\n'
);
const cell = value =>
  String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');
write(
  'http-acceptance-routes.md',
  [
    '# Complete native route input inventory',
    '',
    'Generated by `http-acceptance-inventory.cjs`. Detailed fields, precedence, source statements and parameter cells are retained in `http-acceptance.json`. Source comparison rows are not claims of full native/domain execution.',
    '',
    '| ID | Method / path | Baseline action | Current owner | Disposition / evidence |',
    '|---|---|---|---|---|',
    ...inventory.rows.map(
      row =>
        `| ${row.id} | ${row.method.toUpperCase()} ${cell(row.path)} | ${cell(row.baseline.file)}:${row.baseline.line ?? '-'} ${cell(row.baseline.action)} | ${cell(row.current.file)} | ${cell(row.disposition)}; ${cell(row.coverageKind)} |`
    ),
    '',
    '## Supplemental mounts and protocols',
    '',
    '| Method | Path | Owner | Disposition |',
    '|---|---|---|---|',
    ...inventory.supplemental.map(
      row => `| ${cell(row.method)} | ${cell(row.path)} | ${cell(row.owner)} | ${cell(row.disposition)} |`
    ),
    '',
    '## Bundled extension registrations',
    '',
    '| Package | Source | Own route declarations | Disposition |',
    '|---|---|---|---|',
    ...inventory.bundled.map(
      row => `| ${cell(row.package)} | ${cell(row.source)} | ${row.routeDeclarations} | ${cell(row.disposition)} |`
    ),
    '',
  ].join('\n')
);
const diff = git(['diff', 'a49366803...HEAD']);
write(
  'http-acceptance-provenance.json',
  JSON.stringify(
    {
      ...inventory.provenance,
      baseline: inventory.baseline,
      diff: {
        command: 'git diff a49366803...HEAD',
        bytes: Buffer.byteLength(diff),
        sha256: crypto.createHash('sha256').update(diff).digest('hex'),
      },
      diffStat: git(['diff', '--stat', 'a49366803...HEAD']),
      commits: { command: 'git log a49366803..HEAD --oneline', output: git(['log', 'a49366803..HEAD', '--oneline']) },
      runtimeFreeze: 'afaf6ef010ff00e4cdf6f98b8bce62daf2c64db4',
    },
    null,
    2
  ) + '\n'
);
console.log(JSON.stringify(inventory.counts, null, 2));
if (inventory.counts.differences || inventory.counts.unresolvedBaselinePatterns) process.exitCode = 1;
