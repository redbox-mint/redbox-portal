// Read-only inventory of a committed tree; never imports the application.
// Usage: node support/specs/sails-retirement/evidence/inventory.cjs [commit]
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
function grep(...args) {
  try {
    return git('grep', ...args)
      .trim()
      .split('\n')
      .filter(Boolean);
  } catch (error) {
    if (error.status === 1) return [];
    throw error;
  }
}
const sourceCommit = git('rev-parse', `${process.argv[2] || 'HEAD'}^{commit}`).trim();
const files = git('ls-tree', '-r', '--name-only', sourceCommit).trim().split('\n');
const pattern =
  'sails|Sails|req\\.(file|param|allParams|validate)|res\\.(view|ok|badRequest|serverError|notFound|forbidden|negotiate|jsonx)|io\\.socket';
const matches = grep('-n', '-I', '-E', pattern, sourceCommit, '--', '.');
const generated = new Set(
  grep('-l', '-I', 'Auto-generated by @researchdatabox/redbox-core loader', sourceCommit, '--', '.').map(line =>
    line.slice(sourceCommit.length + 1)
  )
);

function owner(file) {
  if (/^(support\/(specs|docs|wiki)\/|.*\.(md|txt|xml)$)/.test(file))
    return ['reference-only', 'Historical/specification/documentation; no executable retirement claim'];
  if (/package-lock\.json$/.test(file)) return ['dependency-lock', 'SR-002 audit; SR-052 installed dependency closure'];
  if (/package\.json$/.test(file))
    return ['package-metadata', 'SR-002 versions; SR-012/SR-018 registration metadata; SR-052 dependencies'];
  if (/^packages\/redbox-dev-tools\//.test(file))
    return ['scaffold-tooling', 'SR-018, SR-053 generated institution applications'];
  if (/^packages\/sails-hook-redbox-pdfgen\//.test(file))
    return ['pdf-hook', 'SR-016 lifecycle; SR-023 activation; SR-043 progress; SR-044 drain'];
  if (/^packages\/sails-hook-redbox-storage-mongo\//.test(file))
    return ['storage-hook', 'SR-015 capabilities/repositories; SR-024 drain; SR-041 streams'];
  if (/^packages\/redbox-hook-dev\//.test(file))
    return ['development-hook', 'SR-018 declarations; SR-032/SR-040 forms/assets; SR-053 scaffold'];
  if (/(^|\/)(test|tests|unit-testing|integration-testing|acceptance-testing)\//.test(file))
    return ['test-harness', 'SR-003 fixtures; SR-030/SR-046 regression; SR-053 bootstrap'];
  if (/^packages\/sails-ng-common\//.test(file))
    return ['shared-contract', 'Framework-independent shared model package; review any executable matches at SR-052'];
  if (/^packages\/agenda-sqs-backend\//.test(file))
    return ['queue-backend', 'SR-023 activation; SR-024 accepted work/drain'];
  if (/^packages\/(raido|rva-registry)\//.test(file))
    return ['generated-client', 'External API clients; historical Sails names do not imply framework use'];
  if (/^(angular|assets|views)\//.test(file))
    return ['browser-views', 'SR-038 auth; SR-039 CSRF; SR-040 EJS/static; SR-043 sails.io clients'];
  if (/^api\//.test(file))
    return [
      generated.has(file) ? 'generated-app-shim' : 'application-owned-api',
      'SR-051 exact generated reconciliation; preserve edited files; SR-053 bootstrap',
    ];
  if (/^config\//.test(file))
    return [
      generated.has(file) ? 'generated-config-shim' : 'application-owned-config',
      'SR-019/SR-020 conversion; SR-051 exact generated reconciliation',
    ];
  if (/^(app(\.integrationtest)?\.js|\.sailsrc|pm2\.json)$/.test(file))
    return ['legacy-entrypoint', 'SR-010 host; SR-011 comparison; SR-050 promotion; SR-052 removal'];
  if (/^packages\/redbox-core\//.test(file)) {
    if (/\/(loader|hooks)\//.test(file))
      return ['core-loader', 'SR-012..SR-018 extensions; SR-022 migrations; SR-051 shims'];
    if (/\/persistence\//.test(file))
      return ['persistence-owner', 'SR-006 owner/shutdown; SR-024 lifetime; SR-025 maintenance'];
    if (/\/services\/RecordTypesService\.ts$/.test(file))
      return ['record-type-pilot', 'SR-008 extraction; SR-009 persisted behavior; SR-029 routes'];
    if (/\/services\/ConfigService\.ts$/.test(file))
      return ['imperative-config', 'SR-019/SR-021 merge, assets, data writes and overrides'];
    if (
      /\/(CoreBase|CoreService|CoreController|bootstrap)\.ts$|\/services\/index\.ts$|\/controllers\/index\.ts$/.test(
        file
      )
    )
      return ['core-lifecycle-cache', 'SR-007/SR-011 instances; SR-022 bootstrap; SR-023 activation'];
    if (/\/(config|middleware)\//.test(file))
      return ['http-config-middleware', 'SR-019 config; SR-028 middleware; SR-038..SR-043 providers'];
    if (/\/(api-routes|policies)\//.test(file))
      return ['route-policy-contract', 'SR-026/SR-027 contracts/policies; SR-031..SR-037 route groups'];
    if (/AgendaQueue|Asynch|Asynch|Cron/.test(file))
      return ['core-background', 'SR-023 producers; SR-024 accepted completion/drain'];
    if (/\/bin\//.test(file)) return ['maintenance-entrypoint', 'SR-025 standalone inactive maintenance'];
    if (/redbox-loader-templates/.test(file)) return ['shim-template', 'SR-051 generator retirement'];
    return ['core-domain', 'SR-031 inventory then SR-032..SR-036 domain groups; SR-040 browser rendering'];
  }
  if (/^typescript\//.test(file)) return ['app-types', 'SR-052 Sails declarations; SR-053 compilation/bootstrap'];
  if (
    /^(support\/|scripts\/|\.circleci\/|\.github\/|Dockerfile|docker|\.vscode\/|\.mocharc|\.nycrc|webpack|tsconfig)/.test(
      file
    )
  )
    return ['build-deployment-tooling', 'SR-002 execution pins; SR-047 artifact checks; SR-053 retirement'];
  if (
    /^(README|AGENTS|CONTRIBUTING|LICENSE|typedoc|\.git|\.docker|\.editor|\.ox|\.prettier|\.eslint|\.npm|\.nvm|\.check)/.test(
      file
    )
  )
    return ['repository-metadata', 'Documentation/tool configuration; SR-002/SR-053 where executable'];
  return ['unclassified', 'Must be reviewed before SR-001 completion'];
}

const byFile = new Map();
for (const match of matches) {
  const parsed = match.match(/^[^:]+:(.*?):(\d+):(.*)$/);
  if (!parsed) throw new Error('Unrecognized git grep output');
  const [, file, line, content] = parsed;
  let item = byFile.get(file);
  if (!item) {
    const [classification, migrationOwner] = owner(file);
    item = {
      file,
      classification,
      migrationOwner,
      generatedHeader: generated.has(file),
      lines: [],
      executableSignalLines: [],
    };
    byFile.set(file, item);
  }
  item.lines.push(Number(line));
  // Names/URLs alone (notably sails-ng-common) are not proof of Sails execution.
  if (
    /\b(?:sails|Sails)\s*[.([]|require\(['"]sails['"]|from ['"]sails['"]|req\.(file|param|allParams|validate)|res\.(view|ok|badRequest|serverError|notFound|forbidden|negotiate|jsonx)|io\.socket/.test(
      content
    )
  )
    item.executableSignalLines.push(Number(line));
}
const entries = [...byFile.values()].sort((a, b) => a.file.localeCompare(b.file));
const counts = {};
for (const entry of entries) counts[entry.classification] = (counts[entry.classification] || 0) + 1;
const manifests = files
  .filter(file => /^(package\.json|packages\/[^/]+\/package\.json|angular\/package\.json)$/.test(file))
  .map(file => {
    const source = git('show', `${sourceCommit}:${file}`);
    const pkg = JSON.parse(source);
    return {
      file,
      name: pkg.name,
      version: pkg.version,
      packageManager: pkg.packageManager ?? null,
      engines: pkg.engines ?? null,
      sails: pkg.sails ?? null,
      sha256: createHash('sha256').update(source).digest('hex'),
    };
  });
const result = {
  sourceCommit,
  method: {
    trackedFiles: files.length,
    pattern,
    committedTreeOnly: true,
    limitation:
      'Text inventory plus manually documented native owners/routes; symbols in comments are candidates, not proof of execution. Ignored/generated working-tree output and installed dependencies require separate probes.',
  },
  counts,
  matchedFiles: entries.length,
  matchedLines: entries.reduce((n, entry) => n + entry.lines.length, 0),
  unclassified: entries.filter(entry => entry.classification === 'unclassified').map(entry => entry.file),
  manifests,
};
console.log(
  JSON.stringify(result, null, 2).slice(0, -2) +
    ',\n  "entries": [\n' +
    entries.map(entry => '    ' + JSON.stringify(entry)).join(',\n') +
    '\n  ]\n}'
);
if (counts.unclassified) process.exitCode = 1;
