import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { getHookProcessingOrder } from '../hooks/hookDiscovery';
import { assertPersistenceConfiguration } from '../persistence/selection';

const guidance =
  'Model registration has been removed. Remove hasModels/registerRedboxModels and migrate callbacks and mappings to services/repositories and declared Prisma fields. SIEM events and attempts both use datastores.mongodb; split model datastores are unsupported. See Persistence-Migration.md.';

/** Always checked, including production starts that reuse cached service shims. */
export function assertRetiredHookRegistrations(appPath: string): void {
  const requireHook = createRequire(path.join(appPath, 'package.json'));
  for (const hook of getHookProcessingOrder(appPath)) {
    if (hook.sails.hasModels === true) throw new Error(`${hook.name}: ${guidance}`);
    const module: unknown = requireHook(hook.name);
    if (module && (typeof module === 'object' || typeof module === 'function')) {
      if (Reflect.has(module, 'registerRedboxModels')) throw new Error(`${hook.name}: ${guidance}`);
      const register = Reflect.get(module, 'registerRedboxConfig');
      if (typeof register === 'function') assertPersistenceConfiguration(Reflect.apply(register, module, []));
    }
  }
}

/** Delete only exact loader output. An edited banner alone is not provenance. */
function generatedModel(content: string): boolean {
  const banner =
    /^'use strict';\n\/\*\*\n \* (\w+) model shim\n \* Auto-generated by @researchdatabox\/redbox-core loader\n \* Provided by: ([@\w./-]+)\n \* Do not edit manually - regenerated when \.regenerate-shims marker exists\n \*\/\n/;
  const match = content.match(banner);
  if (!match) return false;
  const [, name, provider] = match;
  const body =
    provider === '@researchdatabox/redbox-core'
      ? `const { WaterlineModels } = require('@researchdatabox/redbox-core');\nmodule.exports = { ...WaterlineModels['${name}'], globalId: '${name}' };\n`
      : `module.exports = { ...require('${provider}').registerRedboxModels()['${name}'], globalId: '${name}' };\n`;
  return content.slice(match[0].length) === body;
}

export async function assertRetiredModelSurfaces(appPath: string): Promise<void> {
  const sailsrc = await fs.readFile(path.join(appPath, '.sailsrc'), 'utf8').catch((error: NodeJS.ErrnoException) => {
    if (error.code === 'ENOENT') return '{}';
    throw error;
  });
  assertPersistenceConfiguration(JSON.parse(sailsrc));
  assertRetiredHookRegistrations(appPath);
  const directory = path.join(appPath, 'api/models');
  const entries = await fs.readdir(directory, { withFileTypes: true }).catch((error: NodeJS.ErrnoException) => {
    if (error.code === 'ENOENT') return [];
    throw error;
  });
  for (const entry of entries) {
    if (entry.isFile() && ['.gitkeep', 'README.md'].includes(entry.name)) continue;
    const file = path.join(directory, entry.name);
    if (entry.isFile() && generatedModel(await fs.readFile(file, 'utf8'))) await fs.unlink(file);
    else throw new Error(`Retired model file ${file} was preserved. Migrate and remove it explicitly. ${guidance}`);
  }
  for (const name of ['models', 'orm', 'persistence']) {
    const file = path.join(appPath, 'config', `${name}.js`);
    const content = await fs.readFile(file, 'utf8').catch((error: NodeJS.ErrnoException) => {
      if (error.code === 'ENOENT') return undefined;
      throw error;
    });
    if (content === undefined) continue;
    const header = `'use strict';\n/**\n * ${name} config shim\n * Auto-generated by @researchdatabox/redbox-core loader\n * Do not edit manually - regenerated when .regenerate-shims marker exists\n *\n * Merges: core config + hook configs (root hookLoadPriority precedence; unlisted hooks use package-name fallback)\n * Debug view: see support/debug-config/resolved.js\n */\nconst { Config, mergeRedboxConfig } = require('@researchdatabox/redbox-core');\n`;
    const tail = content.slice(header.length);
    const imports = tail.split('\n\n')[0];
    const bindings = imports
      ? imports
          .split('\n')
          .map(line => line.match(/^const (\w+) = require\('[@\w./-]+'\)\.registerRedboxConfig\(\);$/)?.[1])
      : [];
    const merge = `mergeRedboxConfig('${name}', Config.${name} || {}${bindings.map(binding => `, ${binding}['${name}'] || {}`).join('')})`;
    const generated =
      content.startsWith(header) &&
      bindings.every(Boolean) &&
      (tail === `${imports}\n\nmodule.exports.${name} = ${merge};\n` ||
        tail === `\n\nmodule.exports.${name} = Config.${name};\n`);
    if (generated) await fs.unlink(file);
    else
      throw new Error(
        `Retired config file ${file} was preserved. Remove its obsolete settings. See Persistence-Migration.md.`
      );
  }
}
