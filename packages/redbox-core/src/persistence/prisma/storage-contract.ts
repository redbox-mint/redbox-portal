import { defineContract, field, model } from '@prisma/orm-mongo/contract-builder';

// Stored workflow transitions and legacy authorization aliases have real core writers.
export const recordFields = {
  _id: field.objectId(),
  redboxOid: field.string().optional(),
  harvestId: field.string().optional(),
  revision: field.double().optional(),
  incarnationId: field.string().optional(),
  lifecycleOperationId: field.string().optional(),
  metaMetadata: field.json().optional(),
  metadata: field.json().optional(),
  workflow: field.json().optional(),
  authorization: field.json().optional(),
  previousWorkflow: field.json().optional(),
  notification: field.json().optional(),
  authorization_edit: field.json().optional(),
  authorization_view: field.json().optional(),
  authorization_editRoles: field.json().optional(),
  authorization_viewRoles: field.json().optional(),
  authorization_editPending: field.json().optional(),
  authorization_viewPending: field.json().optional(),
  figshareSyncIntent: field.json().optional(),
  recordVersion: field.double().optional(),
  dateCreated: field.string().optional(),
  lastSaveDate: field.string().optional(),
  createdAt: field.string().optional(),
  updatedAt: field.string().optional(),
};

// Native schema Dates and model/audit ISO strings retain their physical representations.
export const contract = defineContract({
  models: {
    Record: model('Record', {
      collection: 'record',
      fields: recordFields,
    }),
    DeletedRecord: model('DeletedRecord', {
      collection: 'deletedrecord',
      fields: {
        _id: field.objectId(),
        redboxOid: field.string().optional(),
        revision: field.double().optional(),
        incarnationId: field.string().optional(),
        brandId: field.string().optional(),
        lifecycleState: field.string().optional(),
        lifecycleOperation: field.json().optional(),
        deletedRecordMetadata: field.json().optional(),
        dateDeleted: field.string().optional(),
        createdAt: field.string().optional(),
        updatedAt: field.string().optional(),
      },
    }),
    RecordIdentity: model('RecordIdentity', {
      collection: 'recordidentity',
      fields: {
        _id: field.objectId(),
        redboxOid: field.string().optional(),
        incarnationId: field.string().optional(),
        createdAt: field.string().optional(),
      },
    }),
    RecordSchemaArtifact: model('RecordSchemaArtifact', {
      collection: 'recordschemaartifact',
      fields: {
        _id: field.objectId(),
        digest: field.string().optional(),
        document: field.json().optional(),
        contractFormat: field.string().optional(),
        completeness: field.string().optional(),
        byteLength: field.double().optional(),
        createdAt: field.date().optional(),
        updatedAt: field.date().optional(),
        lastAccessedAt: field.date().optional(),
      },
    }),
    RecordSchemaReference: model('RecordSchemaReference', {
      collection: 'recordschemareference',
      fields: {
        _id: field.objectId(),
        referenceKey: field.string().optional(),
        digest: field.string().optional(),
        kind: field.string().optional(),
        brand: field.string().optional(),
        portal: field.string().optional(),
        schemaKind: field.string().optional(),
        recordType: field.string().optional(),
        oid: field.string().optional(),
        operation: field.string().optional(),
        owner: field.string().optional(),
        purpose: field.string().optional(),
        expiresAt: field.date().optional(),
        createdAt: field.date().optional(),
        updatedAt: field.date().optional(),
      },
    }),
    RecordAudit: model('RecordAudit', {
      collection: 'recordaudit',
      fields: {
        _id: field.objectId(),
        redboxOid: field.string().optional(),
        occurredAt: field.string().optional(),
        user: field.json().optional(),
        record: field.json().optional(),
        dateCreated: field.string().optional(),
        action: field.string().optional(),
        executionSummary: field.json().optional(),
        concurrency: field.json().optional(),
        createdAt: field.string().optional(),
        updatedAt: field.string().optional(),
      },
    }),
    IntegrationAudit: model('IntegrationAudit', {
      collection: 'integrationaudit',
      fields: {
        _id: field.objectId(),
        redboxOid: field.string().optional(),
        brandId: field.string().optional(),
        integrationName: field.string().optional(),
        integrationAction: field.string().optional(),
        triggeredBy: field.string().optional(),
        status: field.string().optional(),
        message: field.string().optional(),
        errorDetail: field.string().optional(),
        httpStatusCode: field.double().optional(),
        traceId: field.string().optional(),
        spanId: field.string().optional(),
        parentSpanId: field.string().optional(),
        startedAt: field.string().optional(),
        completedAt: field.string().optional(),
        durationMs: field.double().optional(),
        requestSummary: field.json().optional(),
        responseSummary: field.json().optional(),
        dateCreated: field.string().optional(),
        createdAt: field.string().optional(),
        updatedAt: field.string().optional(),
      },
    }),
    BrandingConfigHistory: model('BrandingConfigHistory', {
      collection: 'brandingconfighistory',
      fields: {
        _id: field.objectId(),
        branding: field.objectId().optional(),
        version: field.double().optional(),
        hash: field.string().optional(),
        css: field.string().optional(),
        variables: field.json().optional(),
        typeface: field.json().optional(),
        actorId: field.string().optional(),
        actorDisplayName: field.string().optional(),
        restoredFromVersion: field.double().optional(),
        dateCreated: field.string().optional(),
        createdAt: field.string().optional(),
        updatedAt: field.string().optional(),
      },
    }),
  },
});
