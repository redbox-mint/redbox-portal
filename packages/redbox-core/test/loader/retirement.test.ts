import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm, access } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { assertRetiredModelSurfaces } from '../../src/loader/retirement';
import { assertPersistenceConfiguration } from '../../src/persistence/selection';
import { resolveDatastore } from '../../src/persistence/mongodb/configuration';

const generatedModel = (name = 'User') =>
  `'use strict';\n/**\n * ${name} model shim\n * Auto-generated by @researchdatabox/redbox-core loader\n * Provided by: @researchdatabox/redbox-core\n * Do not edit manually - regenerated when .regenerate-shims marker exists\n */\nconst { WaterlineModels } = require('@researchdatabox/redbox-core');\nmodule.exports = { ...WaterlineModels['${name}'], globalId: '${name}' };\n`;
const generatedConfig = (name: string) =>
  `'use strict';\n/**\n * ${name} config shim\n * Auto-generated by @researchdatabox/redbox-core loader\n * Do not edit manually - regenerated when .regenerate-shims marker exists\n *\n * Merges: core config + hook configs (root hookLoadPriority precedence; unlisted hooks use package-name fallback)\n * Debug view: see support/debug-config/resolved.js\n */\nconst { Config, mergeRedboxConfig } = require('@researchdatabox/redbox-core');\nconst institution_config = require('institution').registerRedboxConfig();\n\nmodule.exports.${name} = mergeRedboxConfig('${name}', Config.${name} || {}, institution_config['${name}'] || {});\n`;

describe('retired persistence surfaces', () => {
  let directory: string;
  beforeEach(async () => {
    directory = await mkdtemp(join(tmpdir(), 'redbox-retirement-'));
    await mkdir(join(directory, 'api/models'), { recursive: true });
    await mkdir(join(directory, 'config'));
    await writeFile(join(directory, 'package.json'), '{}');
  });
  afterEach(async () => rm(directory, { recursive: true, force: true }));
  it('removes only exact generated model and obsolete config shims on repeated starts', async () => {
    await writeFile(join(directory, 'api/models/User.js'), generatedModel());
    for (const name of ['models', 'orm', 'persistence'])
      await writeFile(join(directory, `config/${name}.js`), generatedConfig(name));
    await assertRetiredModelSurfaces(directory);
    await assertRetiredModelSurfaces(directory);
    await assert.rejects(access(join(directory, 'api/models/User.js')));
    for (const name of ['models', 'orm', 'persistence'])
      await assert.rejects(access(join(directory, `config/${name}.js`)));
  });
  for (const kind of ['custom-model', 'edited-model', 'edited-config']) {
    it(`preserves ${kind} and refuses startup with institution guidance`, async () => {
      const filename = join(directory, kind === 'edited-config' ? 'config/models.js' : 'api/models/Institution.js');
      const source =
        kind === 'custom-model'
          ? 'module.exports = { custom: true };\n'
          : (kind === 'edited-config' ? generatedConfig('models') : generatedModel('Institution')) +
            '// institution edit\n';
      await writeFile(filename, source);
      await assert.rejects(assertRetiredModelSurfaces(directory), /preserved.*(?:migrate|Migrate|obsolete)/);
      assert.equal(await readFile(filename, 'utf8'), source);
    });
  }
  for (const variant of ['flag', 'export', 'config']) {
    it(`rejects stale institution ${variant} registrations before loading Sails`, async () => {
      await mkdir(join(directory, 'node_modules/institution'), { recursive: true });
      await writeFile(join(directory, 'package.json'), JSON.stringify({ dependencies: { institution: '1.0.0' } }));
      await writeFile(
        join(directory, 'node_modules/institution/package.json'),
        JSON.stringify({
          name: 'institution',
          main: 'index.js',
          sails: { isHook: true, ...(variant === 'flag' ? { hasModels: true } : {}) },
        })
      );
      await writeFile(
        join(directory, 'node_modules/institution/index.js'),
        variant === 'export'
          ? 'exports.registerRedboxModels = () => ({});'
          : variant === 'config'
            ? 'exports.registerRedboxConfig = () => ({ models: { securityevent: { datastore: "other" } } });'
            : 'module.exports = {};'
      );
      await assert.rejects(
        assertRetiredModelSurfaces(directory),
        /(?:Model registration has been removed|split model datastores are unsupported)/
      );
    });
  }
  it('rejects all explicit selectors, including former defaults, without exposing values', () => {
    for (const backend of ['waterline', 'mongodb', 'prisma', '', null])
      assert.throws(
        () => assertPersistenceConfiguration({ persistence: { cache: { backend } } }),
        /selectors have been removed/
      );
    for (const name of [
      'RBPORTAL_STORAGE_BACKEND',
      'sails_persistence__groups__siem__backend',
      'sails__persistence__cache__backend',
    ]) {
      const previous = process.env[name];
      try {
        for (const value of ['prisma', 'waterline', '']) {
          process.env[name] = value;
          assert.throws(() => assertPersistenceConfiguration({}), /Remove.*RBPORTAL/);
        }
      } finally {
        if (previous === undefined) delete process.env[name];
        else process.env[name] = previous;
      }
    }
  });
  it('rejects retired model/ORM/datastore settings with replacement keys', () => {
    for (const config of [{ models: {} }, { orm: {} }, { hooks: { orm: true } }])
      assert.throws(() => assertPersistenceConfiguration(config), /(?:model configuration|ORM hook override)/);
    assert.doesNotThrow(() => assertPersistenceConfiguration({ hooks: { orm: false } }));
    assert.doesNotThrow(() => assertPersistenceConfiguration({ globals: { models: false } }));
    assert.throws(() => assertPersistenceConfiguration({ globals: { models: true } }), /Model globals have been removed/);
    assert.throws(
      () => assertPersistenceConfiguration({ datastores: { unused: { adapter: 'obsolete' } } }),
      /including unused datastores/
    );
    for (const name of ['adapter', 'identity', 'schema', 'forceLoadAdapter', 'migrate', 'dontUseObjectIds'])
      assert.throws(
        () => resolveDatastore({ url: 'mongodb://secret:private@host/db', [name]: 'obsolete' }),
        /Keep URL, split credentials\/database/
      );
  });
});
